def client_kb(username: str | None = None, user_id: int | None = None) -> dict | None:
    """Кнопка «написать клиенту» в уведомлении для владельца."""
    if username:
        return {
            "inline_keyboard": [
                [{"text": f"💬 Написать @{username}", "url": f"https://t.me/{username}"}]
            ]
        }
    if user_id:
        return {
            "inline_keyboard": [
                [{"text": "💬 Открыть чат с клиентом", "url": f"tg://user?id={user_id}"}]
            ]
        }
    return None
